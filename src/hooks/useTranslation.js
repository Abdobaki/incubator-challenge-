export function useTranslation() {
  const { lang, switchLang } = useLanguage();

  const t = (key) => {
    const d = dict[lang];
    if (!d) return key;
    return d[key] || dict.en[key] || key;
  };

  const localeData = (obj, field) => {
    if (!obj) return '';
    if (lang === 'fr') return obj[field + 'Fr'] || obj[field] || '';
    if (lang === 'ar') return obj[field + 'Ar'] || obj[field] || '';
    return obj[field] || '';
  };

  return { t, localeData, lang, switchLang, languages: langMap };
}
